#!/usr/bin/env python3
"""
OneFamily Version Header Generator
Reads version.properties and generates include/onefamily_version.h
"""

import os
import sys

def parse_properties(filepath):
    props = {}
    if not os.path.exists(filepath):
        return props
    with open(filepath, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or line.startswith(";"):
                continue
            if "=" in line:
                k, v = line.split("=", 1)
                props[k.strip()] = v.strip()
    return props

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_dir = os.path.dirname(script_dir)
    props_path = os.path.join(project_dir, "version.properties")
    include_dir = os.path.join(project_dir, "include")
    header_path = os.path.join(include_dir, "onefamily_version.h")

    props = parse_properties(props_path)
    major = int(props.get("VERSION_MAJOR", 1))
    minor = int(props.get("VERSION_MINOR", 2))
    patch = int(props.get("VERSION_PATCH", 2))
    prerelease = props.get("VERSION_PRERELEASE", "").strip()
    title = props.get("VERSION_TITLE", "Multi-Controller Engine").strip()

    base_ver = f"{major}.{minor}.{patch}"
    raw_ver = f"{base_ver}-{prerelease}" if prerelease else base_ver
    version_string = f"v{raw_ver}"
    sfo_ver = f"{major:02d}.{minor}{patch}"[:5]
    full_ver = f"{version_string} ({title})" if title else version_string

    header_content = f"""/*
 * Auto-generated by scripts/generate_version.py - DO NOT EDIT MANUALLY
 * Source: version.properties
 */

#ifndef ONEFAMILY_VERSION_H
#define ONEFAMILY_VERSION_H

#define ONEFAMILY_VERSION_MAJOR     {major}
#define ONEFAMILY_VERSION_MINOR     {minor}
#define ONEFAMILY_VERSION_PATCH     {patch}
#define ONEFAMILY_VERSION_RAW       "{raw_ver}"
#define ONEFAMILY_VERSION_STRING    "{version_string}"
#define ONEFAMILY_VERSION_SFO       "{sfo_ver}"
#define ONEFAMILY_VERSION_TITLE     "{title}"
#define ONEFAMILY_VERSION_FULL      "{full_ver}"

#endif // ONEFAMILY_VERSION_H
"""

    os.makedirs(include_dir, exist_ok=True)

    existing_content = ""
    if os.path.exists(header_path):
        with open(header_path, "r", encoding="utf-8") as f:
            existing_content = f.read()

    if existing_content != header_content:
        with open(header_path, "w", encoding="utf-8") as f:
            f.write(header_content)
        print(f"[VERSION] Synchronized include/onefamily_version.h -> {version_string}")
    else:
        print(f"[VERSION] include/onefamily_version.h already up to date ({version_string})")

if __name__ == "__main__":
    main()
